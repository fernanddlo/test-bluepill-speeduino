/**
 * @file main.cpp
 * @brief Speeduino-style ECU core - STM32F103C8T6
 *
 * V0.1
 *
 * Hardware:
 *   STM32F103C8T6
 *
 * Inputs:
 *   PA10 - RPM
 *   PA0  - TPS
 *   PA1  - MAP
 *   PA2  - IAT
 *   PA3  - CLT
 *   PA4  - O2
 *
 * Outputs:
 *   PA8  - INJ1
 *   PA9  - INJ2
 *   PA11 - IGN1
 *   PA12 - IGN2
 *   PB0  - Fuel Pump
 *
 * Communication:
 *   PB10 - USART3 TX
 *   PB11 - USART3 RX
 */

#include "STM32_specific.h"
#include "config.h"

#include "rpm.h"
#include "sensors.h"
#include "fuel_pump.h"
#include "injection.h"
#include "maps.h"
#include "serial_protocol.h"

#include <stdint.h>

// ============================================================
// GLOBAL ENGINE STATE
// ============================================================

volatile EngineState engine_state = ENGINE_OFF;

// ============================================================
// 100 Hz scheduler flag
// ============================================================

volatile uint8_t ecu_10ms_flag = 0;

// ============================================================
// APPLICATION INITIALIZATION
// ============================================================

static void ECU_Init(void)
{
    // --------------------------------------------------------
    // RPM
    // --------------------------------------------------------

    RPM_Init();

    // --------------------------------------------------------
    // Sensors
    // --------------------------------------------------------

    Sensors_Init();

    // --------------------------------------------------------
    // Fuel pump
    // --------------------------------------------------------

    FuelPump_Init();

    // --------------------------------------------------------
    // Injection
    // --------------------------------------------------------

    Injection_Init();

    // --------------------------------------------------------
    // Maps
    // --------------------------------------------------------

    Serial_Init();

    // --------------------------------------------------------
    // Engine state
    // --------------------------------------------------------

    engine_state = ENGINE_OFF;
}

// ============================================================
// 10 ms ENGINE TASK
// ============================================================

static void ECU_Task_10ms(void)
{
    // --------------------------------------------------------
    // RPM processing
    // --------------------------------------------------------

    RPM_Process();

    uint32_t rpm = RPM_Get();

    // --------------------------------------------------------
    // Sensor processing
    // --------------------------------------------------------

    if (rpm == 0)
    {
        engine_state = ENGINE_OFF;
    }
    else if (rpm < MIN_RPM_FOR_RUNNING)
    {
        engine_state = ENGINE_CRANKING;
    }
    else
    {
        engine_state = ENGINE_RUNNING;
    }

    // --------------------------------------------------------
    // Fuel pump
    // --------------------------------------------------------

    FuelPump_Process(rpm);

    Sensors_ReadAll();

    float load = Sensors_GetMAP();

    Injection_Process(
        rpm,
        load
    );
}

// ============================================================
// MAIN
// ============================================================

int main(void)
{
    // --------------------------------------------------------
    // Hardware
    // --------------------------------------------------------

    STM32_Init();

    // --------------------------------------------------------
    // ECU modules
    // --------------------------------------------------------

    ECU_Init();

    // --------------------------------------------------------
    // Main loop
    // --------------------------------------------------------

    while (1)
    {
        if (ecu_10ms_flag)
        {
            ecu_10ms_flag = 0;

            ECU_Task_10ms();
        }
    }
}